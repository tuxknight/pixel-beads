export function closestColor(hex: string, palette: Palette): string {
  const r = parseInt(hex.slice(1, 3), 16)
  const g = parseInt(hex.slice(3, 5), 16)
  const b = parseInt(hex.slice(5, 7), 16)

  let minDist = Infinity
  let closest = palette.colors[0].hex

  for (const c of palette.colors) {
    const cr = parseInt(c.hex.slice(1, 3), 16)
    const cg = parseInt(c.hex.slice(3, 5), 16)
    const cb = parseInt(c.hex.slice(5, 7), 16)
    const dist = (r - cr) ** 2 + (g - cg) ** 2 + (b - cb) ** 2
    if (dist < minDist) {
      minDist = dist
      closest = c.hex
    }
  }

  return closest
}
